    /// <summary>Picks the label set of the language of a client; the one place a document's language is chosen.</summary>
    /// <param name="language">The ISO 639-1 language code of the client, or null when none is set.</param>
    /// <returns>The set for <c>ru</c>, <c>hy</c>, <c>de</c> or <c>es</c>, otherwise English.</returns>
    public static DocumentPdfLabels For(string? language) =>
        language?.Trim().ToLowerInvariant() switch
        {
            "ru" => Russian,
            "hy" => Armenian,
            "de" => German,
            "es" => Spanish,
            _ => English,
        };
}
