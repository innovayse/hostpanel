using Innovayse.Hostpanel.Application.Admin.Common;
using Innovayse.Hostpanel.Application.Admin.Common.Enums;
using Innovayse.Hostpanel.Application.Common.Interfaces;
using Innovayse.Hostpanel.Infrastructure.Storage.Settings;
using Microsoft.AspNetCore.Hosting;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Innovayse.Hostpanel.Infrastructure.Storage;

/// <summary>
/// Writes rendered branding files under the web root and reports their URLs.
/// </summary>
/// <remarks>
/// <para>
/// <b>Each upload gets its own directory, named by a fresh identifier.</b> A new logo therefore
/// never overwrites the previous one. Two reasons, and the second is the one that bites: a
/// browser and every proxy in front of it cache <c>/uploads/branding/logo.png</c> aggressively,
/// so overwriting in place ships an operator a stale logo they cannot clear; and until the
/// setting row is updated the old files are still the live ones, so overwriting would swap the
/// storefront's logo before the operator pressed Save.
/// </para>
/// <para>
/// An upload is removed when the setting that referenced it is saved with another value
/// (<see cref="RemoveAsync"/>, called by the settings update): until then it may still be the live
/// file, so the upload itself never deletes anything. An upload that was previewed and never saved
/// stays on disk; a sweep of directories no setting references would be a scheduled job.
/// </para>
/// </remarks>
public sealed class FileSystemBrandingStorage : IBrandingStorage
{
    /// <summary>Host environment, for locating the web root.</summary>
    private readonly IWebHostEnvironment _env;

    /// <summary>Resolved branding paths and ceilings.</summary>
    private readonly BrandingOptions _options;

    /// <summary>Log sink.</summary>
    private readonly ILogger<FileSystemBrandingStorage> _logger;

    /// <summary>Initializes a new instance of the <see cref="FileSystemBrandingStorage"/> class.</summary>
    /// <param name="env">Host environment, for locating the web root.</param>
    /// <param name="options">Branding paths and ceilings.</param>
    /// <param name="logger">Log sink.</param>
    public FileSystemBrandingStorage(IWebHostEnvironment env, IOptions<BrandingOptions> options, ILogger<FileSystemBrandingStorage> logger)
    {
        _env = env;
        _options = options.Value;
        _logger = logger;
    }

    /// <inheritdoc />
    public async Task<IReadOnlyList<BrandingAssetDto>> SaveAsync(
        BrandingKind kind,
        IReadOnlyList<BrandingRendition> renditions,
        CancellationToken ct)
    {
        var uploadsRoot = UploadsRoot();

        // "logo" / "logodark" / "logomark" / "favicon" come from an enum, not from the request,
        // so this segment cannot be steered by a caller.
        var kindSegment = kind.ToString().ToLowerInvariant();
        var uploadId = Guid.NewGuid().ToString("n");

        var targetDir = Path.Combine(uploadsRoot, kindSegment, uploadId);
        Directory.CreateDirectory(targetDir);

        var assets = new List<BrandingAssetDto>(renditions.Count);

        foreach (var rendition in renditions)
        {
            ct.ThrowIfCancellationRequested();

            var fileName = SafeFileName(rendition.FileName);
            var filePath = Path.Combine(targetDir, fileName);

            // Defence in depth. Every name here is generated by the processor, so this should
            // never fail; if an uploaded name ever reaches this method, the write is refused
            // rather than landing outside the uploads root. The guard sits at the write itself,
            // not in a caller trusted to get it right.
            var resolved = Path.GetFullPath(filePath);
            if (!resolved.StartsWith(uploadsRoot + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            {
                throw new InvalidOperationException(
                    $"Refusing to write branding file outside the uploads root: {rendition.FileName}");
            }

            await File.WriteAllBytesAsync(resolved, rendition.Content, ct);

            // Always forward slashes: this is a URL path, and Path.Combine would produce
            // backslashes on Windows that a browser reads as literal characters.
            var url = $"/{_options.RelativePath.Trim('/')}/{kindSegment}/{uploadId}/{fileName}";

            assets.Add(new BrandingAssetDto(url, rendition.ContentType, rendition.PixelSize, rendition.Role));
        }

        _logger.LogInformation(
            "Stored {Count} {Kind} branding file(s) under {Directory}.",
            assets.Count, kindSegment, targetDir);

        return assets;
    }

    /// <inheritdoc />
    public Task RemoveAsync(string url, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(url);
        ct.ThrowIfCancellationRequested();

        // Only a URL of the exact shape SaveAsync issues names an upload: /<root>/<kind>/<id>/<file>.
        // Anything else (an external address, an older path, a hand-typed value) is not ours to delete.
        var prefix = $"/{_options.RelativePath.Trim('/')}/";
        if (!url.StartsWith(prefix, StringComparison.Ordinal))
        {
            return Task.CompletedTask;
        }

        var segments = url[prefix.Length..].Split('/');
        var isUpload = segments.Length == 3
            && Enum.GetNames<BrandingKind>().Any(k => string.Equals(k.ToLowerInvariant(), segments[0], StringComparison.Ordinal))
            && Guid.TryParseExact(segments[1], "n", out _);
        if (!isUpload)
        {
            return Task.CompletedTask;
        }

        var uploadDir = Path.GetFullPath(Path.Combine(UploadsRoot(), segments[0], segments[1]));
        if (Directory.Exists(uploadDir))
        {
            Directory.Delete(uploadDir, recursive: true);
            _logger.LogInformation("Removed the superseded branding upload {Directory}.", uploadDir);
        }

        return Task.CompletedTask;
    }

    /// <summary>The absolute directory every upload is written under.</summary>
    /// <returns>The uploads root, resolved against the web root.</returns>
    private string UploadsRoot()
    {
        var webRoot = _env.WebRootPath ?? Path.Combine(_env.ContentRootPath, "wwwroot");
        return Path.GetFullPath(Path.Combine(webRoot, _options.RelativePath));
    }

    /// <summary>
    /// Reduces a rendition name to a bare filename.
    /// </summary>
    /// <param name="fileName">The name the processor chose.</param>
    /// <returns>The name with any directory component removed.</returns>
    /// <exception cref="InvalidOperationException">The name is empty or has no usable part.</exception>
    private static string SafeFileName(string fileName)
    {
        var bare = Path.GetFileName(fileName);

        return string.IsNullOrWhiteSpace(bare) || bare is "." or ".."
            ? throw new InvalidOperationException($"Unusable branding file name: '{fileName}'.")
            : bare;
    }
}
