/**
 * The languages the portal is published in; the codes are the URL prefixes and `X-Language` values.
 *
 * @module types/applocale
 */
export enum AppLocale {
  /** English, the default language: served without a URL prefix. */
  En = 'en',
  /** Russian. */
  Ru = 'ru',
  /** Armenian. */
  Hy = 'hy',
  /** French. */
  Fr = 'fr'
}
